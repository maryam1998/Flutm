import 'dart:math' as math;

/// وزشِ بادِ گاه‌به‌گاه 🍃 برای علف و گل.
///
/// بیشترِ وقت‌ها هوا آرام است و گیاه‌ها ساکن‌اند؛ هر از گاهی یک وزشِ نرم می‌آید،
/// گیاه‌ها کمی خم می‌شوند و آرام تکان می‌خورند، و دوباره آرام می‌شود.
/// وزش در افقِ صفحه حرکت می‌کند (گیاه‌های چپ و راست هم‌زمان تکان نمی‌خورند).
///
/// [t] زمان به ثانیه، [x] مختصاتِ افقیِ گیاه، [phase] فازِ ثابتِ هر گیاه.
/// خروجی تقریباً بین -۰٫۴ و ۱٫۳ است (ضرب در دامنه‌ی دلخواه).
double windSway(double t, double x, double phase) {
  final u = t - x * 0.004;
  // دو موجِ کند با دوره‌ی ~۱۷ و ~۲۷ ثانیه؛ فقط وقتی هر دو بالا باشند وزش می‌آید
  final a = math.sin(u * 0.37) + math.sin(u * 0.23 + 1.7);
  final k = ((a - 1.0) / 1.0).clamp(0.0, 1.0).toDouble();
  final gust = k * k * (3 - 2 * k);
  if (gust <= 0.0) return 0.0;
  // خم‌شدن در جهتِ باد + نوسانِ آرام
  return gust * (0.8 + 0.5 * math.sin(t * 2.0 + phase));
}
