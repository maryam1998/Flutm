import 'dart:math' as math;

/// نسیمِ ملایم 🍃 برای علف، برگ، غنچه و گل.
///
/// یک نسیمِ آرام تقریباً همیشه می‌وزد (موجِ کندی که در افقِ صفحه حرکت می‌کند، پس
/// گیاه‌های چپ و راست هم‌زمان تکان نمی‌خورند)، ولی هر گیاه چرخه‌ی تصادفیِ خودش را
/// هم دارد: بعضی‌ها یک مدت ساکن‌اند و بعضی در حال تکان خوردن؛ هر از گاهی هم جایشان
/// عوض می‌شود. گذار بین ساکن و متحرک نرم است.
///
/// [t] زمان به ثانیه، [x] مختصاتِ افقیِ گیاه، [phase] فازِ ثابتِ هر گیاه (هر عددی).
/// خروجی تقریباً بین ۰ و ۱٫۶ است (ضرب در دامنه‌ی دلخواه).
double windSway(double t, double x, double phase) {
  final u = t - x * 0.004;
  // نسیمِ کلی: همیشه کمی هست، گاهی کمی قوی‌تر
  final breeze = 0.6 + 0.4 * math.sin(u * 0.5 + 0.9 * math.sin(u * 0.19));
  // چرخه‌ی ساکن/متحرکِ خودِ این گیاه (دو موجِ کند با دوره‌ی ~۲۳ و ~۳۷ ثانیه)
  final ph = phase * 7.31 + 1.3;
  final m = math.sin(t * 0.27 + ph) + math.sin(t * 0.17 + ph * 1.9 + 2.0);
  final k = (m + 0.6).clamp(0.0, 1.0).toDouble();
  final act = k * k * (3 - 2 * k);
  if (act <= 0.0) return 0.0;
  // خم‌شدن در جهتِ باد + نوسانِ آرام
  final wave =
      0.62 * math.sin(t * 1.7 + ph + x * 0.013) + 0.38 * math.sin(t * 2.9 + ph * 2.3);
  return act * breeze * (0.8 + 0.8 * wave);
}
